/**
 * Returns a fresh copy of the 26 A-Z placeholder teams for the Control Deck grid.
 */
export function getControlDeckPlaceholderTeams() {
  return REFERENCE_TEAM_ROSTER.map((team, idx) => ({
    ...team,
    id: `team-${team.slotKey.toLowerCase()}`,
    rank: idx + 1,
    players: [...team.players],
  }));
}

/**
 * Returns the 8 sample leaderboard teams for the Phase 1 Broadcast Overlay Viewport.
 */
export function getOverlaySampleLeaderboard() {
  return REFERENCE_TEAM_ROSTER.slice(0, 8).map((team, idx) => ({
    rank: idx + 1,
    slotKey: team.slotKey,
    teamName: team.teamName,
    tag: team.tag,
    kp: team.kp,
    pp: team.pp,
    tt: team.tt,
    aliveCount: team.aliveCount,
    status: team.status,
  }));
}
